export function getMiningDurationSeconds(blockId: BlockId, heldStack: ItemStack | null): number {
  const block = BLOCKS[blockId];
  if (!block || block.hardness < 0) return Infinity;
  if (block.hardness === 0) return 0.05;

  const tool = heldStack ? ITEMS[heldStack.id] : null;
  let speedMultiplier = 1;
  let canHarvest = block.minTier === 0;

  if (tool && tool.toolCategory && tool.toolCategory === block.preferredTool) {
    speedMultiplier = tool.miningSpeed ?? 1;
    if ((tool.toolTier ?? 0) >= block.minTier) {
      canHarvest = true;
    }
    if (heldStack?.enchantment?.id === 'efficiency') {
      speedMultiplier += heldStack.enchantment.level * 2.5;
    }
  } else if (tool?.toolCategory === 'sword' && (block.id === BlockId.OakLeaves || block.id === BlockId.BirchLeaves || block.id === BlockId.SpruceLeaves)) {
    speedMultiplier = 3;
  }

  const base = canHarvest ? block.hardness * 1.5 : block.hardness * 5.0;
  return Math.max(0.06, base / speedMultiplier);
}

export function canHarvestBlock(blockId: BlockId, heldItemId: ItemId | null): boolean {
  const block = BLOCKS[blockId];
  if (!block || block.minTier === 0) return true;
  const tool = heldItemId ? ITEMS[heldItemId] : null;
  if (!tool || tool.toolCategory !== block.preferredTool) return false;
  return (tool.toolTier ?? 0) >= block.minTier;
}
